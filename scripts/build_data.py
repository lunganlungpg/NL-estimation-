"""Write every bundled dataset to data/*.csv and data/nonlinear_datasets.xlsx.

The package (nlsfit/datasets.py) is the single source of truth; this script
just exports it so the data can be opened in Excel, R, SPSS, etc.

Run:  python scripts/build_data.py
"""

from pathlib import Path

import numpy as np
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from nlsfit import datasets

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "data"
HEADER = PatternFill("solid", fgColor="0E7490")
NIST_FILL = PatternFill("solid", fgColor="E0F2FE")
SIM_FILL = PatternFill("solid", fgColor="FEF3C7")


def _style_header(ws, row=1):
    for cell in ws[row]:
        if cell.value is not None:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = HEADER
            cell.alignment = Alignment(vertical="center", wrap_text=True)


def _autowidth(ws, max_width=60):
    for col in ws.columns:
        width = max(len(str(c.value)) if c.value is not None else 0 for c in col)
        ws.column_dimensions[get_column_letter(col[0].column)].width = min(max(width + 2, 10), max_width)


def _fmt(v):
    return ", ".join(f"{p:.10g}" for p in v) if v is not None else ""


def main():
    OUT.mkdir(exist_ok=True)
    names = datasets.list_datasets()
    wb = Workbook()

    about = wb.active
    about.title = "README"
    rows = [
        ["Nonlinear estimation sample datasets"],
        [],
        [
            "What is this?",
            "Datasets for practising nonlinear least squares (Gauss–Newton, Levenberg–Marquardt).",
        ],
        [
            "Sheets",
            "'Index' lists every dataset with its model, source and true/certified values. "
            "Each dataset sheet holds only its two data columns, so it reads cleanly into R or Python.",
        ],
        ["", "'NIST certified' gives the official answers and starting values for the NIST problems."],
        ["", "'Your data' is a blank template: paste x and y, then fit with nlsfit or the website."],
        ["Kinds", "nist = NIST StRD reference problem with certified answers (public domain)."],
        ["", "real = published experimental data."],
        ["", "simulated = generated by nlsfit from known true parameters (shown in the Index)."],
        ["Python", "import nlsfit; d = nlsfit.datasets.load('puromycin'); nlsfit.fit(d.model, d.x, d.y)"],
        ["pandas", "pd.read_excel('nonlinear_datasets.xlsx', sheet_name='puromycin')"],
        ["Source of NIST data", "https://www.itl.nist.gov/div898/strd/nls/nls_main.shtml"],
    ]
    for r in rows:
        about.append(r)
    about["A1"].font = Font(bold=True, size=14)
    for r in range(3, len(rows) + 1):
        about.cell(r, 1).font = Font(bold=True)
    about.column_dimensions["A"].width = 22
    about.column_dimensions["B"].width = 100

    index = wb.create_sheet("Index")
    index.append(
        [
            "dataset",
            "kind",
            "n",
            "model",
            "formula",
            "parameters",
            "x",
            "y",
            "certified / true values",
            "difficulty",
            "description",
            "source",
        ]
    )
    for name in names:
        d = datasets.load(name)
        values = d.certified if d.certified is not None else d.true_params
        index.append(
            [
                name,
                d.kind,
                int(d.x.size),
                d.model.name,
                d.model.formula,
                ", ".join(d.model.param_names),
                d.x_label,
                d.y_label,
                _fmt(values),
                d.difficulty,
                d.description,
                d.source,
            ]
        )
        fill = NIST_FILL if d.kind == "nist" else SIM_FILL if d.kind == "simulated" else None
        if fill:
            for cell in index[index.max_row]:
                cell.fill = fill
    _style_header(index)
    _autowidth(index)
    index.freeze_panes = "B2"

    nist = wb.create_sheet("NIST certified")
    nist.append(["dataset", "parameter", "certified value", "start 1", "start 2", "certified residual SS"])
    for name in names:
        d = datasets.load(name)
        if d.kind != "nist":
            continue
        for j, pname in enumerate(d.model.param_names):
            nist.append(
                [
                    name,
                    pname,
                    d.certified[j],
                    d.starts[0][j],
                    d.starts[1][j],
                    d.certified_sse if j == 0 else None,
                ]
            )
    _style_header(nist)
    _autowidth(nist)
    for row in nist.iter_rows(min_row=2, min_col=3, max_col=6):
        for cell in row:
            cell.number_format = "0.0000000000E+00"

    for name in names:
        d = datasets.load(name)
        ws = wb.create_sheet(name[:31])
        ws.append([d.x_label, d.y_label])
        for xi, yi in zip(d.x, d.y, strict=True):
            ws.append([float(xi), float(yi)])
        _style_header(ws)
        ws.column_dimensions["A"].width = max(14, len(d.x_label) + 2)
        ws.column_dimensions["B"].width = max(14, len(d.y_label) + 2)
        ws.freeze_panes = "A2"

        header = f"{d.x_label},{d.y_label}"
        np.savetxt(
            OUT / f"{name}.csv",
            np.column_stack([d.x, d.y]),
            delimiter=",",
            header=header,
            comments="",
            fmt="%.10g",
        )

    tpl = wb.create_sheet("Your data")
    tpl.append(["x", "y", "", "Paste your data in columns A and B (no blank rows)."])
    _style_header(tpl)
    tpl.column_dimensions["D"].width = 60

    wb.save(OUT / "nonlinear_datasets.xlsx")
    print(f"Wrote {len(names)} CSV files and data/nonlinear_datasets.xlsx")


if __name__ == "__main__":
    main()
